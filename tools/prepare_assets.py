"""Refresh homepage critical CSS and content-based asset versions. Standard library only."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
START = '<!-- Generated by tools/prepare_assets.py: start -->'
END = '<!-- Generated by tools/prepare_assets.py: end -->'


class Classes(HTMLParser):
    def __init__(self):
        super().__init__()
        self.names = set()

    def handle_starttag(self, tag, attrs):
        self.names.update(dict(attrs).get('class', '').split())


def css_rules(source):
    """Read complete blocks, respecting quoted braces and nested media queries."""
    source = re.sub(r'/\*.*?\*/', '', source, flags=re.S)
    source = re.sub(r'@charset\s+[^;]+;', '', source)
    start = 0
    depth = 0
    quote = None
    escaped = False
    opening = None
    for i, char in enumerate(source):
        if escaped:
            escaped = False
            continue
        if char == '\\':
            escaped = True
            continue
        if quote:
            if char == quote:
                quote = None
            continue
        if char in ('"', "'"):
            quote = char
        elif char == '{':
            if depth == 0:
                opening = i
            depth += 1
        elif char == '}':
            depth -= 1
            if depth == 0:
                yield source[start:opening].strip(), source[opening + 1:i]
                start = i + 1
            if depth < 0:
                raise ValueError('Unbalanced CSS')
    if depth or quote or source[start:].strip():
        raise ValueError('Unsupported or incomplete CSS')


def critical_css(source, classes):
    result = []
    for selector, body in css_rules(source):
        if selector.startswith(('@media', '@supports', '@layer')):
            body = critical_css(body, classes)
            if body:
                result.append(selector + '{' + body + '}')
        elif selector.startswith('@keyframes'):
            result.append(selector + '{' + body + '}')
        elif selector.startswith('@'):
            raise ValueError('Review new CSS at-rule: ' + selector)
        else:
            names = set(re.findall(r'\.([a-zA-Z_][\w-]*)', selector))
            if not names or names & classes:
                result.append(selector + '{' + body + '}')
    return ''.join(result)


def version_urls(source, document):
    def replace(match):
        url = match.group(1)
        parsed = urlsplit(url)
        if parsed.netloc and parsed.netloc != 'sulin1122.github.io':
            return match.group(0)
        if parsed.scheme and parsed.scheme != 'https':
            return match.group(0)
        path = ((ROOT / parsed.path.lstrip('/')) if parsed.path.startswith('/')
                else (document.parent / parsed.path)).resolve()
        if not path.is_relative_to(ROOT) or not path.is_file():
            raise ValueError('Missing or external asset: ' + url)
        version = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
        return url + '?v=' + version
    pattern = (r'(?<=[\s\"\'])((?:https://[^/\s\"\']+/)?(?:\.\.?/)*'
               r'[a-zA-Z0-9][\w./-]*\.(?:css|js|webp|svg|jpg|png|ico))(?:\?v=[\w.-]+)?')
    if document.suffix == '.html':
        def attribute(match):
            value = re.sub(pattern, replace, ' ' + match.group(2))[1:]
            return match.group(1) + value + match.group(3)
        return re.sub(r'(\b(?:src|href|srcset|imagesrcset|content)=\")(.*?)(\")', attribute, source)
    return re.sub(pattern, replace, source)


def write_if_changed(path, source):
    if path.read_text(encoding='utf-8') != source:
        path.write_text(source, encoding='utf-8', newline='\n')


def main():
    # Image versions must be refreshed before hashing the scripts that use them.
    for name in ['myScript.js', 'todo.js']:
        path = ROOT / name
        write_if_changed(path, version_urls(path.read_text(encoding='utf-8'), path))

    home = ROOT / 'index.html'
    html = home.read_text(encoding='utf-8')
    classes = Classes()
    classes.feed(html[html.index('<body>'):html.index('<section class="collection')])
    classes.names.update(['motion-paused', 'section-light', 'section-meta', 'collection'])
    critical = critical_css((ROOT / 'style.css').read_text(encoding='utf-8'), classes.names)
    if len(critical.encode('utf-8')) > 16000 or '</style' in critical.lower():
        raise ValueError('Review homepage critical CSS size/content')
    block = (START + '\n  <style id="critical-css">' + critical + '</style>\n'
             '  <link rel="stylesheet" href="./style.css" media="print" '
             'onload="this.onload=null;this.media=\'all\'">\n'
             '  <noscript><link rel="stylesheet" href="./style.css"></noscript>\n  ' + END)
    if START in html:
        html, count = re.subn(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, html, flags=re.S)
    else:
        html, count = re.subn(r'<link rel="stylesheet" href="\./style\.css[^\"]*">', lambda _: block, html)
    if count != 1:
        raise ValueError('Expected one homepage stylesheet block')
    write_if_changed(home, html)

    for path in sorted(ROOT.rglob('*.html')):
        write_if_changed(path, version_urls(path.read_text(encoding='utf-8'), path))
    print(f'Updated asset versions; homepage critical CSS: {len(critical.encode("utf-8"))} bytes')


if __name__ == '__main__':
    main()
